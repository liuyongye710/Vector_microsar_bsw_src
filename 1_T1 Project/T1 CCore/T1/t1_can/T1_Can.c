Std_ReturnType T1_CanTransmit(const uint8 *pData,uint16 nOfBytes)
{
    Std_ReturnType Result = E_OK;
    PduInfoType pdu;
    pdu.SduDataPtr = (uint8 *)pData;
    pdu.SduLength = nOfBytes;
    Result = CanIf_Transmit(CANIF_TX_PDU_CFG_GL_TX_RES_VOXYRF_INDEX,&pdu);

    return Result;
}

